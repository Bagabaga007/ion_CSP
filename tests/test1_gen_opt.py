@patch("pyxtal.pyxtal")
@patch("os.makedirs")
def test_generate_structures_success(
    mock_makedirs, mock_pyxtal, crystal_generator: CrystalGenerator, tmp_path: Path
):
    """测试结构生成成功路径"""
    # 模拟 pyxtal 成功生成
    mock_structure = MagicMock()
    mock_structure.to_file = MagicMock()
    mock_pyxtal.return_value = mock_structure

    # 模拟生成 5 个结构，分布在 2 个空间群
    mock_structure.from_random.side_effect = [None, None, None, None, None]

    # 模拟异常不触发
