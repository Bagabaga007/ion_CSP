def test_dpdisp_mlp_tasks_local_gpu(
    mock_sleep,
    mock_check_output,
    mock_environ,
    mock_remove,
    mock_makedirs,
    mock_rmtree,
    mock_copy,
    mock_chdir,
    mock_load_resources,
    mock_load_machine,
    crystal_generator: CrystalGenerator,
    tmp_path: Path,
):
    """测试本地 GPU 模式"""
    # 模拟 GPU 可用
    mock_check_output.return_value = (
        "0,10,1024\n1,20,1024\n2,50,1024\n"  # GPU 0,1,2，内存占用 10%,20%,50%
    )
    mock_load_machine.return_value.serialize.return_value = {
        "context_type": "LocalContext",
        "batch_type": "Shell",
    }
    mock_load_resources.return_value.serialize.return_value = {
        "number_node": 1,
        "cpu_per_node": 4,
        "gpu_per_node": 1,
    }

    # 创建文件
    for i in range(4):
        (crystal_generator.primitive_cell_dir / f"POSCAR_{i}").write_text(
            "dummy", encoding="utf-8"
        )

    # 模拟任务分发
    crystal_generator.dpdisp_mlp_tasks(
        machine=str(tmp_path / "machine.json"),
        resources=str(tmp_path / "resources.json"),
        nodes=2,
    )

    # 验证
    mock_check_output.assert_called_once()
    mock_environ.__setitem__.assert_called_once_with("CUDA_VISIBLE_DEVICES", "0")
    mock_chdir.assert_called_once_with(str(crystal_generator.primitive_cell_dir))

    # 验证复制了文件
    mock_copy.assert_any_call(
        str(crystal_generator.mlp_opt_file),
        str(crystal_generator.primitive_cell_dir / "mlp_opt.py"),
    )
    mock_copy.assert_any_call(
        str(crystal_generator.model_file),
        str(crystal_generator.primitive_cell_dir / "model.pt"),
    )

    # 验证 task_list 创建
    # 4 个文件，2 个节点 → [0,2], [1,3]
    # 每个节点有 2 个 forward_files + 2 个 backward_files + 2 个 POSCAR
    # 验证提交了 2 个 task
    # （dpdispatcher 的 Task/Submission 会被 mock，但调用次数应为 2）

    # 验证清理
    mock_remove.assert_any_call(
        str(crystal_generator.primitive_cell_dir / "mlp_opt.py")
    )
    mock_remove.assert_any_call(str(crystal_generator.primitive_cell_dir / "model.pt"))
    mock_rmtree.assert_called()  # 至少调用了一次 pop{n} 目录


